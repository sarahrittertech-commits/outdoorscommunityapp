"""Writes town-map.md from towns.json and the area config: every town Sarah
has sent, under its big region and area (live or future), plus a by-state
view for deciding whether states become a level. Run from the repo root:
python3 scripts/research/town-map.py"""
import json, re
from collections import defaultdict

d = json.load(open("scripts/research/towns.json"))
regions = open("src/config/regions.ts").read()
areas = {m[0]: (m[1], m[2]) for m in re.findall(r'slug: "([a-z-]+)",\s*group: "([a-z-]+)",\s*name: "([^"]+)"', regions)}
groups = dict(re.findall(r'\{ slug: "([a-z-]+)", name: "([^"]+)"', open("src/config/regionGroups.ts").read()))
groups[None] = "No big region yet"

def st(t):
    return t.rsplit(", ", 1)[1][:2]

by_group = defaultdict(list)
for slug, towns in d["live"].items():
    g, name = areas[slug]
    by_group[g].append((name, "live", towns))
for name, towns in d["next"].items():
    by_group[d["next_regions"][name]].append((name, "future", towns))

out = ["# Town map", "",
       "Generated by `scripts/research/town-map.py` from `towns.json`. Every town Sarah has sent, under the big region and area it best fits (nearest area center, 100 miles). **Live** areas are open on the board; **future** areas are where research is kept until an area opens. The big region for a future area is a soft mapping for review.", ""]
for g in list(groups):
    if g not in by_group:
        continue
    out += [f"## {groups[g]}", "", "| Area | Status | States | Towns |", "| --- | --- | --- | --- |"]
    for name, status, towns in sorted(by_group[g], key=lambda x: (x[1], x[0])):
        states = ", ".join(sorted({st(t) for t in towns}))
        out.append(f"| {name} | {status} | {states} | {'; '.join(towns)} |")
    out.append("")

state_areas = defaultdict(set)
for g, rows in by_group.items():
    for name, status, towns in rows:
        for t in towns:
            state_areas[st(t)].add(f"{name} ({status})")
out += ["## By state", "", "Which areas each state's towns fall in, for deciding whether states become a level between big region and area.", "", "| State | Areas |", "| --- | --- |"]
for s in sorted(state_areas):
    out.append(f"| {s} | {'; '.join(sorted(state_areas[s]))} |")
open("scripts/research/town-map.md", "w").write("\n".join(out) + "\n")
print("wrote scripts/research/town-map.md")
