#!/usr/bin/env node
// Regions, one-off data move: puts each group already on the board in the
// region its area is in. Until 11 October 2026 every group was in
// western-nc; groups whose area is a town in another region (Raleigh-area
// groups to triangle, Seattle-area to puget-sound, ...) move.
//
//   # 1. Export the groups (Supabase SQL editor, or psql) as JSON:
//   #    select json_agg(json_build_object('id', g.id, 'area', g.area,
//   #      'region_id', g.region_id, 'region_slug', r.slug))
//   #    from public.groups g join public.regions r on r.id = g.region_id;
//   # 2. Turn it into SQL, read it, then run it:
//   node scripts/regions/assign-regions.mjs < groups.json > assign.sql
//
//   # Or print one statement that does the same from a VALUES list of town
//   # names, with no export needed:
//   node scripts/regions/assign-regions.mjs --values > assign.sql
//
// Input: a JSON array of { id, area, region_id, region_slug? } on stdin.
// Output: one `update public.groups ... where id = ...` per group whose area
// matches a town (src/config/towns.ts) in a different region, each guarded
// so it changes nothing if the group is already there. Areas that match no
// town are listed in a comment at the end, to sort out by hand on each
// group's edit page.
//
// Matching mirrors lib/geo townForArea: the whole area, then the part before
// " and ", then the part before a comma; "Name, ST" and "Name, State" find
// the town in that state; a plain name used in two states means the default
// region's town (Fayetteville is the one in North Carolina).
//
// Needs Node 23.6 or later (it reads towns.ts directly, stripping types).
// The regions must exist first: supabase/migrations/20261011000001_regions.sql.

import { readFileSync } from "node:fs";

import { towns } from "../../src/config/towns.ts";

const DEFAULT_REGION = "western-nc";
const STATE_NAMES = {
  CO: "Colorado",
  KY: "Kentucky",
  NC: "North Carolina",
  TN: "Tennessee",
  VA: "Virginia",
  WA: "Washington",
  WV: "West Virginia",
};

const byName = new Map();
const add = (key, town) => {
  if (!byName.has(key.toLowerCase())) byName.set(key.toLowerCase(), town);
};
for (const t of towns.filter((t) => t.region === DEFAULT_REGION)) add(t.name, t);
for (const t of towns) {
  add(t.name, t);
  add(`${t.name}, ${t.state}`, t);
  if (STATE_NAMES[t.state]) add(`${t.name}, ${STATE_NAMES[t.state]}`, t);
  for (const a of t.aliases ?? []) add(a, t);
}

const find = (text) => (text ? byName.get(text.trim().replace(/\s+/g, " ").toLowerCase()) : undefined);

/** The town a group's free-text area names, as lib/geo townForArea. */
export function townForArea(area) {
  if (!area) return undefined;
  const first = area.split(/\s+and\s+/)[0];
  return find(area) ?? find(first) ?? find(first.split(",")[0]);
}

const sql = (s) => `'${String(s).replaceAll("'", "''")}'`;

if (process.argv.includes("--values")) {
  // Every name a town outside the default region goes by. The longest match
  // wins, so "Fayetteville, WV" beats "Fayetteville".
  const rows = [];
  for (const t of towns.filter((t) => t.region && t.region !== DEFAULT_REGION)) {
    const names = new Set([`${t.name}, ${t.state}`, ...(t.aliases ?? [])]);
    if (STATE_NAMES[t.state]) names.add(`${t.name}, ${STATE_NAMES[t.state]}`);
    // A plain name only when it means this town (not a default-region one).
    if (find(t.name) === t) names.add(t.name);
    for (const n of names) rows.push(`    (${sql(n)}, ${sql(t.region)})`);
  }
  console.log(`-- Regions: move groups whose area is a town in another region (generated by scripts/regions/assign-regions.mjs --values).
with m(town, slug) as (
  values
${rows.join(",\n")}
),
hit as (
  select distinct on (g.id) g.id, m.slug
  from public.groups g
  join m on lower(btrim(g.area)) = lower(m.town)
         or lower(btrim(g.area)) like lower(m.town) || ' and %'
         or lower(btrim(g.area)) like lower(m.town) || ',%'
  order by g.id, length(m.town) desc
)
update public.groups g
   set region_id = r.id
  from hit
  join public.regions r on r.slug = hit.slug
 where g.id = hit.id
   and g.region_id <> r.id;`);
  process.exit(0);
}

let groups;
try {
  groups = JSON.parse(readFileSync(0, "utf8"));
} catch {
  console.error("Expected a JSON array of { id, area, region_id } on stdin. See the comment at the top of this file.");
  process.exit(1);
}
if (!Array.isArray(groups)) {
  console.error("Expected a JSON array.");
  process.exit(1);
}

const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const out = ["-- Regions: move groups to the region their area is in (generated by scripts/regions/assign-regions.mjs).", "begin;"];
const unmatched = [];
let moves = 0;
for (const g of groups) {
  if (!uuid.test(g?.id ?? "")) continue;
  const town = townForArea(g.area);
  if (!town?.region) {
    unmatched.push(g);
    continue;
  }
  if (g.region_slug && g.region_slug === town.region) continue;
  moves++;
  out.push(
    `update public.groups set region_id = r.id from public.regions r where r.slug = ${sql(town.region)} and groups.id = ${sql(g.id)} and groups.region_id <> r.id; -- ${String(g.area).replaceAll("\n", " ")}`,
  );
}
out.push("commit;");
out.push(`-- ${moves} group(s) to move.`);
if (unmatched.length) {
  out.push(`-- ${unmatched.length} group(s) whose area matches no town in a region (left where they are):`);
  for (const g of unmatched) out.push(`--   ${g.id}  ${String(g.area ?? "").replaceAll("\n", " ")}`);
}
console.log(out.join("\n"));
